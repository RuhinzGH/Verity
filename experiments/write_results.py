"""Write RESULTS.md from results/*.json, so every number in it is computed, not typed.

    python -m experiments.write_results
"""
import json

from verity.config import RESULTS, ROOT


def load(name):
    p = RESULTS / f"{name}.json"
    if not p.exists() and name == "e06_ragtruth":          # older partial-run file name
        p = RESULTS / "e06_ragtruth_sentences.json"
    return json.loads(p.read_text()) if p.exists() else None


def f3(x):
    return "n/a" if x is None else f"{x:.3f}"


def ci(r):
    lo, hi = r["macro_f1_ci95"]
    return f"{r['macro_f1']:.3f} [{lo:.3f}, {hi:.3f}]"


def main():
    out = ["# Verity: results", "",
           "Generated by `python -m experiments.write_results` from the JSON files in `results/`.",
           "Square brackets are 95% bootstrap confidence intervals (1,000 resamples). Unless a section",
           "says otherwise (3b and 8 use three seeds), runs use seed 42 and a single training run, so",
           "differences inside an interval are not evidence of a real difference.", ""]

    r = load("e01_retrieval")
    if r:
        out += ["## 1. Retrieval: finding the evidence", ""]
        for key, title in [("scifact_dev", "SciFact dev"), ("climate_fever", "Climate-FEVER")]:
            b = r[key]
            out += [f"**{title}** - {b['n_claims']} claims with evidence, {b['n_passages']:,} passages", "",
                    "| Method | Recall@1 | Recall@5 | Recall@10 | MRR@10 | nDCG@10 | ms / query |",
                    "|---|---|---|---|---|---|---|"]
            for m, v in b["methods"].items():
                out.append(f"| {m} | {f3(v['recall@1'])} | {f3(v['recall@5'])} | {f3(v['recall@10'])} | "
                           f"{f3(v['mrr@10'])} | {f3(v['ndcg@10'])} | {v['ms_per_query']} |")
            out.append("")

    r = load("e02_verifiers")
    if r:
        out += ["## 2. Verification with oracle evidence", "",
                "Confidence intervals resample whole claims (Climate-FEVER has five evidence pairs per claim).",
                "NEI evidence is length-matched to the rationales, so evidence length does not give the label",
                "away; the mean length per label is listed under each table.", ""]
        for key, title in [("scifact_dev", "SciFact dev"), ("climate_fever", "Climate-FEVER, all 6,905 pairs"),
                           ("climate_fever_sample", "Climate-FEVER, balanced sample of 300 pairs")]:
            if key not in r:
                continue
            ms = {m: v for m, v in r[key].items() if not m.startswith("_")}
            out += [f"**{title}**", "", "| Verifier | n | Accuracy | Macro-F1 [95% CI] | ECE |", "|---|---|---|---|---|"]
            for m, v in ms.items():
                pe = f" ({v['parse_errors']} unparsed)" if v.get("parse_errors") else ""
                out.append(f"| {m}{pe} | {v['n']} | {f3(v['accuracy'])} | {ci(v)} | {f3(v['ece'])} |")
            any_v = next(iter(ms.values()))
            if "majority_baseline_accuracy" in any_v:
                out.append(f"| always the most common label | {any_v['n']} | {f3(any_v['majority_baseline_accuracy'])} | | |")
            fmt = r[key].get("_evidence_format")
            if fmt:
                out += ["", "Evidence length by label: " + "; ".join(
                    f"{l} {v['mean_sentences']:.2f} sentences / {v['mean_chars']:.0f} characters" for l, v in fmt.items())]
            out.append("")

    r = load("e03_finetune")
    if r:
        out += ["## 3. Fine-tuning", "",
                f"Base `{r['base']}`, {r['epochs']} epochs, learning rate {r['lr']}, batch {r['batch']}, "
                f"max length {r['max_length']}, on {r['fit_pairs']} SciFact training pairs "
                f"({', '.join(f'{k} {v}' for k, v in r['fit_label_counts'].items())}); "
                f"{r['calibration_pairs']} pairs (from 20% of the claims) held out for calibration. "
                f"GPU: {r['gpu']}, peak memory {r['peak_gpu_memory_gb']} GB, "
                f"{r['log'][-1]['minutes']} minutes.", ""]

    r = load("e03b_seeds")
    if r:
        out += ["### 3b. Seeds and a class-balanced variant", "",
                f"The fine-tuning recipe trained with seeds {', '.join(map(str, r['seeds']))}, plus a variant whose loss "
                "is weighted by inverse class frequency. Mean ± standard deviation over the three seeds. The recipes "
                f"are compared on the calibration claims; better there: **{r['better_on_calibration']}**. "
                + r["note"], "",
                "| Recipe | Calibration macro-F1 | Dev macro-F1 | Dev accuracy | Dev ECE | Dev recall S / R / NEI |",
                "|---|---|---|---|---|---|"]
        for k, v in r["summary"].items():
            rc = v["dev_recall_mean"]
            out.append(f"| {k} | {v['calibration_macro_f1']['mean']:.3f} ± {v['calibration_macro_f1']['sd']:.3f} | "
                       f"{v['dev_macro_f1']['mean']:.3f} ± {v['dev_macro_f1']['sd']:.3f} | "
                       f"{v['dev_accuracy']['mean']:.3f} ± {v['dev_accuracy']['sd']:.3f} | "
                       f"{v['dev_ece']['mean']:.3f} ± {v['dev_ece']['sd']:.3f} | "
                       f"{rc['SUPPORTED']:.2f} / {rc['REFUTED']:.2f} / {rc['NEI']:.2f} |")
        out.append("")

    r = load("e04_conformal")
    if r:
        out += ["## 4. Calibration and conformal uncertainty", "",
                f"Calibration set: {r['n_calibration']} pairs, one per held-out SciFact training claim (the same "
                "claims as experiment 3's held-out set, which also counts their extra hard-negative pairs).", "",
                "| Verifier | Test set | Temperature | ECE before | ECE after | Coverage at 90% target | Mean set size | Share confident | Accuracy when confident |",
                "|---|---|---|---|---|---|---|---|---|"]
        for m, v in r["models"].items():
            for t, tv in v["tests"].items():
                c = tv["conformal"]["0.1"]
                out.append(f"| {m} | {t} | {v['temperature']:.2f} | {f3(tv['ece_before'])} | {f3(tv['ece_after'])} | "
                           f"{f3(c['coverage'])} | {c['mean_set_size']:.2f} | {f3(c['share_confident'])} | "
                           f"{f3(c['accuracy_when_confident'])} |")
        out.append("")

    r = load("e05_end_to_end")
    if r:
        out += ["## 5. End to end on SciFact dev (retrieve, then verify)", "",
                f"{r['n_claims']} claims, top {r['top_docs']} abstracts per claim.", "",
                "| Retriever + verifier | Accuracy | Macro-F1 [95% CI] | Evidence in top 3 |", "|---|---|---|---|"]
        for k, v in r["runs"].items():
            out.append(f"| {k} | {f3(v['accuracy'])} | {ci(v)} | {f3(v['evidence_hit@3'])} |")
        out.append("")

    r = load("e05b_evidence_design")
    if r:
        out += ["### 5b. How the evidence is cut from an abstract", "",
                f"Design chosen on the calibration claims, before looking at dev: **{r['chosen_on_calibration']}**.", "",
                "Experiment 5 had already been run on dev when this was set up; the choice itself uses calibration claims only.", "",
                "The last two columns apply the uncertainty labels exactly as the app does (experiment 4's temperature",
                "and 90% threshold, fitted on oracle evidence) and measure what they deliver on retrieved evidence.", "",
                "| Design + verifier | Calibration macro-F1 | Dev macro-F1 [95% CI] | Dev coverage at 90% target | Dev share confident |",
                "|---|---|---|---|---|"]
        for k in r["dev"]:
            pc = r["dev"][k].get("pipeline_conformal_at_90", {})
            out.append(f"| {k} | {f3(r['calibration'][k]['macro_f1'])} | {ci(r['dev'][k])} | "
                       f"{f3(pc.get('coverage'))} | {f3(pc.get('share_confident'))} |")
        out.append("")

    for name, title in [("e06_ragtruth", "## 6. Hallucination detection on RAGTruth")]:
        r = load(name)
        if not r:
            continue
        out += [title, "", f"{r['n_test']} test answers (balanced by task and label); thresholds chosen on "
                f"{r['n_train']} training answers.", "",
                "| Method | F1 [95% CI] | Precision | Recall | Correct answers flagged | AUROC [95% CI] | Sentence F1 | QA F1 | Summary F1 | Data2txt F1 |",
                "|---|---|---|---|---|---|---|---|---|---|"]

        def rng(v, key="f1_ci95"):
            return f" [{v[key][0]:.3f}, {v[key][1]:.3f}]" if key in v else ""
        for m, v in r["methods"].items():
            bt, rs = v["by_task"], v["response"]
            au = f"{f3(v['auroc'])}{rng(v, 'auroc_ci95')}" if "auroc" in v else "n/a (no score)"
            out.append(f"| {m} | {f3(rs['f1'])}{rng(rs)} | {f3(rs['precision'])} | {f3(rs['recall'])} | "
                       f"{f3(v.get('clean_answers_flagged'))} | {au} | {f3(v.get('sentence', {}).get('f1'))} | "
                       f"{f3(bt['QA']['f1'])} | {f3(bt['Summary']['f1'])} | {f3(bt['Data2txt']['f1'])} |")
        r8 = load("e08_scale_up") or {}
        if "ragtruth_judge_32b" in r8:
            v = r8["ragtruth_judge_32b"]
            rs, bt = v["response"], v["by_task"]
            out.append(f"| qwen2.5-32b judge (cloud GPU, experiment 8) | {f3(rs['f1'])}{rng(rs)} | {f3(rs['precision'])} | "
                       f"{f3(rs['recall'])} | {f3(v.get('clean_answers_flagged'))} | n/a (no score) | | "
                       f"{f3(bt['QA']['f1'])} | {f3(bt['Summary']['f1'])} | {f3(bt['Data2txt']['f1'])} |")
        b = r["always_flag_baseline"]
        out += [f"| flag every answer (baseline) | {f3(b['f1'])}{rng(b)} | {f3(b['precision'])} | {f3(b['recall'])} | 1.000 | 0.5 | | | | |", ""]

    r = load("e07_error_analysis")
    if r:
        out += ["## 7. Where it fails", ""]
        for k, v in r.items():
            ms_ = v.get("mistakes_on_supported", {})
            extra = (f" Mistakes on supported claims: {ms_['total']}, of which {ms_['said_nei']} were 'not enough evidence' "
                     f"({ms_['said_nei_confident_over_0.9']} with confidence above 0.9).") if ms_ else ""
            out += [f"**{k}** (fine-tuned verifier, oracle evidence, accuracy {f3(v['accuracy'])}, n = {v['n']} pairs).{extra}", "",
                    "| Trait of the claim | Pairs with it | Accuracy with | Accuracy without | Gap |", "|---|---|---|---|---|"]
            for t, tv in v["traits"].items():
                out.append(f"| {t} | {tv['n_with']} | {f3(tv['acc_with'])} | {f3(tv['acc_without'])} | {tv['gap']:+.3f} |")
            out += ["", "Confusion (rows = true label, columns = predicted):", "",
                    "| | " + " | ".join(v["confusion"]) + " |", "|---|---|---|---|"]
            for t, row in v["confusion"].items():
                out.append(f"| {t} | " + " | ".join(str(x) for x in row.values()) + " |")
            out.append("")

    r = load("e08_scale_up")
    if r:
        r2 = load("e02_verifiers") or {}
        out += ["## 8. Laptop GPU vs cloud GPU", "",
                f"Run on {r.get('gpu', 'a cloud GPU')} with the same data, splits, prompts and metrics. "
                "Only the models are bigger (the large verifier also uses learning rate 1e-5 and batch 16, "
                "its usual settings). The core system above runs on the 4 GB laptop GPU.", "",
                "| Judge | Where | SciFact dev macro-F1 | Climate-FEVER sample macro-F1 |", "|---|---|---|---|"]

        def lap(name, key):
            v = r2.get(key, {}).get(name)
            return ci(v) if v else "n/a"
        out.append(f"| fine-tuned DeBERTa-v3-base (184M) | laptop | {lap('verity-finetuned', 'scifact_dev')} | "
                   f"{lap('verity-finetuned', 'climate_fever_sample')} |")
        if "large_summary" in r:
            ls = r["large_summary"]
            out.append(f"| fine-tuned DeBERTa-v3-large (435M), mean ± sd of {len(r['large_runs'])} seeds | cloud | "
                       f"{ls['scifact_dev']['mean']:.3f} ± {ls['scifact_dev']['sd']:.3f} | "
                       f"{ls['climate_fever_sample']['mean']:.3f} ± {ls['climate_fever_sample']['sd']:.3f} |")
        for name in ("qwen2.5-1.5b", "qwen2.5-3b"):
            if name in r2.get("scifact_dev", {}):
                out.append(f"| {name} LLM judge | laptop | {lap(name, 'scifact_dev')} | {lap(name, 'climate_fever_sample')} |")
        check = r.get("check_14b", {})
        for name, j in r.get("judges", {}).items():
            flag = ""
            if name == "qwen2.5-14b":
                u = check.get("qwen2.5-14b_unbatched_50")
                flag = (f" (check: unbatched accuracy on 50 claims {u['accuracy']:.2f}, agreement with batched "
                        f"{u['agrees_with_batched']:.2f})") if u else " (under investigation: see note)"
            cells = [ci(j[k]) if k in j else "n/a" for k in ("scifact_dev", "climate_fever_sample")]
            out.append(f"| {name} LLM judge{flag} | cloud | {cells[0]} | {cells[1]} |")
        if "ragtruth_judge_32b" in r:
            rj = r["ragtruth_judge_32b"]["response"]
            out += ["", f"RAGTruth, Qwen2.5-32B reading whole answers: F1 {rj['f1']:.3f} "
                    f"[{rj['f1_ci95'][0]:.3f}, {rj['f1_ci95'][1]:.3f}], precision {rj['precision']:.3f}, "
                    f"recall {rj['recall']:.3f}, correct answers flagged "
                    f"{r['ragtruth_judge_32b']['clean_answers_flagged']:.3f} (n = {r['ragtruth_judge_32b']['n_test']})."]
        out.append("")

    missing = [n for n in ["e01_retrieval", "e02_verifiers", "e03_finetune", "e03b_seeds", "e04_conformal", "e05_end_to_end",
                           "e05b_evidence_design", "e06_ragtruth", "e07_error_analysis", "e08_scale_up"] if load(n) is None]
    r2 = load("e02_verifiers") or {}
    if r2 and not any(k.startswith(("qwen", "gpt")) for k in r2.get("scifact_dev", {})):
        missing.append("e02_verifiers (LLM judges)")
    if missing:
        out += ["## Not yet run in this build", "", *[f"- `{m}`" for m in missing], ""]
    (ROOT / "RESULTS.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote", ROOT / "RESULTS.md")
    readme_headline()


def readme_headline():
    """Refresh the README block between the results markers with computed headline numbers."""
    rows = []
    r1, r2, r4, r5, r5b, r6 = (load(n) for n in ["e01_retrieval", "e02_verifiers", "e04_conformal",
                                                   "e05_end_to_end", "e05b_evidence_design", "e06_ragtruth"])
    if r1:
        m = r1["climate_fever"]["methods"]
        rows.append(f"| Retrieval, Climate-FEVER Recall@10 | BM25 {f3(m['bm25']['recall@10'])} | "
                    f"hybrid {f3(m['hybrid']['recall@10'])} |")
    if r2:
        s = r2["scifact_dev"]
        rows.append("| *Oracle rows: the verifier is handed the annotated evidence.* | | |")
        rows.append(f"| Verifier macro-F1, SciFact dev (oracle evidence) | zero-shot {ci(s['deberta-fever'])} | "
                    f"fine-tuned {ci(s['verity-finetuned'])} |")
        c = r2.get("climate_fever")
        if c:
            rows.append(f"| Verifier macro-F1, Climate-FEVER, all 6,905 pairs (out of domain) | zero-shot {ci(c['deberta-fever'])} | "
                        f"fine-tuned {ci(c['verity-finetuned'])} |")
    if r4:
        t = r4["models"]["verity-finetuned"]["tests"]
        rows.append(f"| Coverage of the 90% uncertainty labels, oracle evidence | SciFact dev {f3(t['scifact_dev']['conformal']['0.1']['coverage'])} | "
                    f"Climate-FEVER {f3(t['climate_fever']['conformal']['0.1']['coverage'])} (shifted data) |")
    if r5b:
        rows.append("| *End-to-end rows: the system finds its own evidence in 5,183 abstracts.* | | |")
        k = r5b["chosen_on_calibration"]
        pc = r5b["dev"][k].get("pipeline_conformal_at_90", {})
        rows.append(f"| End-to-end macro-F1, SciFact dev (design chosen on held-out claims) | {k} | {ci(r5b['dev'][k])} |")
        if pc:
            rows.append(f"| Coverage of the 90% uncertainty labels, end to end | {k} | {f3(pc['coverage'])} |")
    if r6:
        fixed = "sentences + verity-finetuned"          # the app's offline configuration, fixed in advance
        v = r6["methods"].get(fixed)
        if v:
            rs, b = v["response"], r6["always_flag_baseline"]
            lo, hi = rs.get("f1_ci95", [float("nan")] * 2)
            rows.append(f"| RAGTruth hallucination-detection F1 (sentence claims + fine-tuned verifier, threshold fitted on RAGTruth train) | {f3(rs['f1'])} [{lo:.3f}, {hi:.3f}] | "
                        f"flag-every-answer baseline {f3(b['f1'])} |")
    block = ["<!-- results:start -->", "**Headline results** (generated from `results/`; brackets are 95% bootstrap CIs)", "",
             "| Measure | Result | Compared with |", "|---|---|---|", *rows, "<!-- results:end -->"]
    p = ROOT / "README.md"
    s = p.read_text(encoding="utf-8")
    a, b = s.index("<!-- results:start -->"), s.index("<!-- results:end -->") + len("<!-- results:end -->")
    p.write_text(s[:a] + "\n".join(block) + s[b:], encoding="utf-8")
    print("updated README headline,", len(rows), "rows")


if __name__ == "__main__":
    main()
